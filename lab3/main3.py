import numpy as np
import matplotlib.pyplot as plt
from matplotlib.animation import FuncAnimation

# ============================================================
# ПАРАМЕТРЫ
# ============================================================

L = 6.0          # длина кабеля, м
m = 2.0          # масса кабеля, кг
g = 9.81         # ускорение свободного падения

# Начальное небольшое смещение
x0 = 0.15

T_MAX = 4.0

# ============================================================
# МОДЕЛЬ ДВИЖЕНИЯ
# ============================================================

# Координата смещения от положения равновесия
# x увеличивается до L/2

x_max = L / 2

# Время моделирования
t = np.linspace(0, T_MAX, 400)

# Для красивой анимации задаём движение через
# энергетическую зависимость.
#
# v = dx/dt = sqrt(2g/L) * x
#
# Решение:
# x(t) = x0 * exp(sqrt(2g/L) * t)

k = np.sqrt(2 * g / L)

x = x0 * np.exp(k * t)

# Ограничиваем движение моментом соскальзывания
mask = x <= x_max

x = x[mask]
t = t[mask]

# Скорость
v = k * x

# Кинетическая энергия
E_kin = 0.5 * m * v**2

# Изменение потенциальной энергии
E_pot_change = m * g * x**2 / L

# Теоретическая скорость в момент соскальзывания
v_end = np.sqrt(g * L / 2)

print(f"Скорость в момент соскальзывания:")
print(f"v = {v_end:.2f} м/с")

# ============================================================
# СОЗДАНИЕ ОКНА
# ============================================================

fig, (ax1, ax2) = plt.subplots(
    1, 2,
    figsize=(13, 6)
)

# ============================================================
# ЛЕВАЯ ПАНЕЛЬ — АНИМАЦИЯ
# ============================================================

ax1.set_xlim(-3, 3)
ax1.set_ylim(-5, 5)

ax1.set_aspect('equal')
ax1.grid(True, alpha=0.3)

ax1.set_title('Соскальзывание однородного кабеля')
ax1.set_ylabel('Высота, м')

# ============================================================
# БЛОК
# ============================================================

theta = np.linspace(0, 2 * np.pi, 100)

pulley_radius = 0.6

ax1.plot(
    pulley_radius * np.cos(theta),
    pulley_radius * np.sin(theta),
    'k-',
    lw=3
)

# Ось блока
ax1.plot(
    [-0.15, 0.15],
    [0, 0],
    'k-',
    lw=4
)

# ============================================================
# КАБЕЛЬ
# ============================================================

cable, = ax1.plot(
    [],
    [],
    'r-',
    lw=6
)

# Точка центра кабеля
center_point, = ax1.plot(
    [],
    [],
    'bo',
    markersize=8
)

# Начальное положение
ax1.plot(
    [-0.6, -0.6],
    [0, -L / 2],
    'k--',
    alpha=0.25
)

ax1.plot(
    [0.6, 0.6],
    [0, -L / 2],
    'k--',
    alpha=0.25
)

# ============================================================
# ИНФОРМАЦИЯ
# ============================================================

text_info = ax1.text(
    -2.7,
    4.2,
    '',
    fontsize=11,
    bbox=dict(
        facecolor='white',
        alpha=0.85
    )
)

# ============================================================
# ПРАВАЯ ПАНЕЛЬ — ЭНЕРГИЯ
# ============================================================

ax2.set_title('Переход потенциальной энергии в кинетическую')

ax2.plot(
    t,
    E_kin,
    'b-',
    lw=2,
    label='Eк'
)

ax2.plot(
    t,
    E_pot_change,
    'r--',
    lw=2,
    label='ΔEпот'
)

ax2.set_xlabel('t, с')
ax2.set_ylabel('Энергия, Дж')

ax2.grid(True)
ax2.legend()

# Точка на графике
energy_point, = ax2.plot(
    [],
    [],
    'ko',
    markersize=8
)

# ============================================================
# ФУНКЦИЯ ОБНОВЛЕНИЯ
# ============================================================

def update(i):

    # Смещение кабеля
    displacement = x[i]

    # Длины вертикальных частей
    left_length = L / 2 + displacement
    right_length = L / 2 - displacement

    # --------------------------------------------------------
    # Координаты кабеля
    # --------------------------------------------------------

    # Левая часть
    left_y = np.linspace(
        0,
        -left_length,
        100
    )

    left_x = np.full_like(
        left_y,
        -0.6
    )

    # Правая часть
    right_y = np.linspace(
        0,
        -right_length,
        100
    )

    right_x = np.full_like(
        right_y,
        0.6
    )

    # Верхняя часть через блок
    theta_cable = np.linspace(
        np.pi,
        0,
        80
    )

    top_x = pulley_radius * np.cos(theta_cable)
    top_y = pulley_radius * np.sin(theta_cable)

    # Собираем весь кабель
    cable_x = np.concatenate([
        left_x,
        top_x,
        right_x
    ])

    cable_y = np.concatenate([
        left_y,
        top_y,
        right_y
    ])

    cable.set_data(
        cable_x,
        cable_y
    )

    # --------------------------------------------------------
    # Центр масс
    # --------------------------------------------------------

    # При смещении центр масс опускается
    center_y = -L / 4 - displacement**2 / L

    center_point.set_data(
        [0],
        [center_y]
    )

    # --------------------------------------------------------
    # Информация
    # --------------------------------------------------------

    text_info.set_text(
        f't = {t[i]:.2f} c\n'
        f'x = {displacement:.2f} м\n'
        f'v = {v[i]:.2f} м/с\n'
        f'Eк = {E_kin[i]:.2f} Дж'
    )

    # --------------------------------------------------------
    # Точка на графике энергии
    # --------------------------------------------------------

    energy_point.set_data(
        [t[i]],
        [E_kin[i]]
    )

    return (
        cable,
        center_point,
        text_info,
        energy_point
    )


# ============================================================
# АНИМАЦИЯ
# ============================================================

ani = FuncAnimation(
    fig,
    update,
    frames=len(t),
    interval=20,
    blit=True
)

plt.tight_layout()
plt.show()